CREATE TABLE TB_RS_ABRIGO (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    nome              VARCHAR2(100) NOT NULL,
    endereco          VARCHAR2(200) NOT NULL,
    bairro            VARCHAR2(100) NOT NULL,
    capacidade        NUMBER(10)    NOT NULL,
    vagas_disponiveis NUMBER(10)    NOT NULL,
    latitude          NUMBER(9,6),
    longitude         NUMBER(9,6),
    ativo             NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_RS_ABRIGO PRIMARY KEY (id),
    CONSTRAINT CK_RS_ABRIGO_ATIVO CHECK (ativo IN (0, 1)),
    CONSTRAINT CK_RS_ABRIGO_VAGAS CHECK (vagas_disponiveis BETWEEN 0 AND capacidade)
);

CREATE TABLE TB_RS_SENSOR (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    codigo      VARCHAR2(20)  NOT NULL,
    localizacao VARCHAR2(200) NOT NULL,
    bairro      VARCHAR2(100) NOT NULL,
    limite_cm   NUMBER(10,2)  NOT NULL,
    ativo       NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_RS_SENSOR PRIMARY KEY (id),
    CONSTRAINT UK_RS_SENSOR_CODIGO UNIQUE (codigo),
    CONSTRAINT CK_RS_SENSOR_ATIVO CHECK (ativo IN (0, 1))
);

CREATE TABLE TB_RS_LEITURA (
    id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    sensor_id NUMBER(19)   NOT NULL,
    nivel_cm  NUMBER(10,2) NOT NULL,
    chuva_mm  NUMBER(10,2) NOT NULL,
    data_hora TIMESTAMP    NOT NULL,
    CONSTRAINT PK_RS_LEITURA PRIMARY KEY (id),
    CONSTRAINT FK_RS_LEITURA_SENSOR FOREIGN KEY (sensor_id) REFERENCES TB_RS_SENSOR (id)
);

CREATE TABLE TB_RS_ALERTA (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    sensor_id  NUMBER(19),
    leitura_id NUMBER(19),
    nivel      VARCHAR2(10)  NOT NULL,
    mensagem   VARCHAR2(300) NOT NULL,
    bairro     VARCHAR2(100) NOT NULL,
    data_hora  TIMESTAMP     NOT NULL,
    ativo      NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_RS_ALERTA PRIMARY KEY (id),
    CONSTRAINT FK_RS_ALERTA_SENSOR FOREIGN KEY (sensor_id) REFERENCES TB_RS_SENSOR (id),
    CONSTRAINT FK_RS_ALERTA_LEITURA FOREIGN KEY (leitura_id) REFERENCES TB_RS_LEITURA (id),
    CONSTRAINT CK_RS_ALERTA_NIVEL CHECK (nivel IN ('ATENCAO', 'PERIGO')),
    CONSTRAINT CK_RS_ALERTA_ATIVO CHECK (ativo IN (0, 1))
);

